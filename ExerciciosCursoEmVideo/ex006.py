"""

Crie um algoritmo que leia um número e mostre o seu dobro, tripo e e a raiz quadrada.

"""

numero = int(input("Informe um número: "))

dobro = numero * 2
tripo = numero * 3
raiz = numero ** (1/2)

print(f"O dobro do seu número: {dobro} \nO tripo o seu número: {tripo} \nA raiz quadrada {raiz}")