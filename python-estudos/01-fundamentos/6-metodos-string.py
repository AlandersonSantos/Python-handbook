"""

==================
METODOS STRING
==================

Métodos, sçao funções próprias do "STR", que permitir manipular, alterar ou consultar.


"""

n = input("Digite algo: ") # Criamos uma variável, que recebe uma informação.


# TYPE() - Método usado para saber qual o tipo de dado.

print(type(n)) #Irá mostrar o resulta de "Class Str", pois o dado é uma string.


# ISNUMERIC() - Método usado para saber se é um número (TRUE) ou não número (FALSE). valor booleano.

print(n.isnumeric())


# ISALPHA() - Método usado para saber se é uma letra (TRUE) ou se não é letra (False). Valor booleano.

print(n.isalpha())


# ISALNUM() - Método usado para saber se é um número e letra (TRUE) ou se não é número ou letra (FALSE). Valor booleano.

print(n.isalnum())


# ISUPPER() - Método usado para saber se todas as letras são maiúsculas (TRUE) ou se não são (FALSE). Valor booleano.

print(n.isupper())


# ISLOWER() - Método usado para saber se todas as letras são minúsculas (TRUE) ou não (FALSE). Valor booleano.

print(n.islower())






